# ── 2. The files ───────────────────────────────────────────────────────────────────────
def poser_fichiers(cible: Path, faire: bool) -> None:
    for chemin, contenu in PAQUET["textes"].items():
        f = cible / chemin
        dire("gris", f"{chemin}  ({len(contenu) // 1024 or 1} kB)")
        if faire:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(contenu, encoding="utf-8")
            if chemin.endswith(".py"):
                f.chmod(0o755)
    for chemin, b64 in PAQUET["images"].items():
        octets = base64.b64decode(b64)
        dire("gris", f"{chemin}  ({len(octets) // 1024} kB)")
        if faire:
            f = cible / chemin
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_bytes(octets)


# ── 3. The icon, with the configuration's initials ─────────────────────────────────────
def faire_icone(cible: Path, conf: dict, faire: bool) -> None:
    """The shipped PNGs carry "AB" and "cd". If Pillow is here, we redraw them as yours.

    ⚠️ Without Pillow the home screen keeps the original initials: it is an image, not text,
    and no configuration changes it afterwards.
    """
    m = conf.get("marque") or {}
    haut, bas = (m.get("haut") or "AB")[:2], (m.get("bas") or "cd")[:2]
    accent = conf.get("accent") or "#E8972E"
    if haut == "AB" and bas == "cd":
        dire("gris", "icon: original initials, nothing to redraw")
        return
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        dire("info", "icon: Pillow missing, it will keep \"AB · cd\"",
             "pip3 install pillow, then run again")
        return
    dire("ok", f"icon redrawn: \"{haut}\" and \"{bas}\", rule {accent}")
    if not faire:
        return
    rvb = tuple(int(accent.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4))
    police = None
    for essai in ("/System/Library/Fonts/Supplemental/Arial Black.ttf",
                  "/System/Library/Fonts/Helvetica.ttc",
                  "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"):
        if Path(essai).exists():
            police = essai
            break
    for taille in (180, 512):
        k = taille / 64
        im = Image.new("RGB", (taille, taille), (0, 0, 0))
        d = ImageDraw.Draw(im)
        f = ImageFont.truetype(police, int(30 * k)) if police else ImageFont.load_default()
        for texte, x, y in ((haut, 32, 30), (bas, 48, 58)):
            b = d.textbbox((0, 0), texte, font=f)
            d.text(((x * k) - (b[2] - b[0]) / 2, (y * k) - b[3]), texte, font=f,
                   fill=(237, 235, 228))
        d.rounded_rectangle([5 * k, 38 * k, 23 * k, 45 * k], radius=2 * k, fill=rvb)
        im.save(cible / "tableau-de-bord" / f"icone-{taille}.png", optimize=True)


# ── 4. The service ─────────────────────────────────────────────────────────────────────
COMPOSE = """services:
  tableau:
    image: nginx:alpine
    # ⛔ 127.0.0.1 and not 0.0.0.0: the door to the private network is opened by
    # `tailscale serve`, never by a port listening on every interface.
    ports:
      - "127.0.0.1:%d:80"
    volumes:
      - ./tableau-de-bord:/usr/share/nginx/html:ro
      - ./tableau-de-bord/nginx.conf:/etc/nginx/conf.d/default.conf:ro
    restart: unless-stopped
""" % PORT


def servir(cible: Path, etat: dict, faire: bool) -> None:
    f = cible / "docker-compose.tableau.yml"
    dire("gris", f"docker-compose.tableau.yml  (port 127.0.0.1:{PORT})")
    if faire:
        f.write_text(COMPOSE, encoding="utf-8")
    if not etat.get("docker"):
        dire("info", "docker missing — serve tableau-de-bord/ with whatever you like",
             f"par exemple : cd tableau-de-bord && python3 -m http.server {PORT} --bind 127.0.0.1")
        return
    if not faire:
        dire("info", f"would start the container on 127.0.0.1:{PORT}")
        return
    code, sortie = lancer(["docker", "compose", "-f", str(f), "up", "-d",
                           "--force-recreate", "tableau"], cwd=cible)
    dire("ok" if code == 0 else "non", "container started" if code == 0 else "container failed",
         "" if code == 0 else sortie[-300:])


# ── 5. Private access ──────────────────────────────────────────────────────────────────
def ouvrir_au_tailnet(etat: dict, faire: bool) -> None:
    if not etat.get("tailscale"):
        dire("info", "tailscale missing — the page stays on the machine",
             "https://tailscale.com, then run again")
        return
    if not faire:
        dire("info", f"would open access: tailscale serve --bg --https=443 http://127.0.0.1:{PORT}")
