# ── 6. The morning refresh ─────────────────────────────────────────────────────────────
def poser_la_tache(cible: Path, heure: int, faire: bool) -> None:
    ligne = f"{0} {heure} * * * cd {cible} && {sys.executable} scripts/tableau-de-bord.py >/dev/null 2>&1"
    dire("gris", f"task: every day at {heure}:00")
    if not faire:
        dire("info", "would add this line to the crontab", ligne)
        return
    code, actuel = lancer(["crontab", "-l"])
    lignes = [l for l in (actuel.splitlines() if code == 0 else []) if "tableau-de-bord.py" not in l]
    lignes.append(ligne)
    p = subprocess.run(["crontab", "-"], input="\n".join(lignes) + "\n", text=True,
                       capture_output=True)
    dire("ok" if p.returncode == 0 else "non",
         f"task set for {heure}:00" if p.returncode == 0 else "crontab refused",
         "" if p.returncode == 0 else p.stderr[-200:])


# ── 7. The figures, a first time ───────────────────────────────────────────────────────
def premiers_chiffres(cible: Path, faire: bool) -> None:
    if not faire:
        dire("info", "would produce the figures a first time")
        return
    code, sortie = lancer([sys.executable, "scripts/tableau-de-bord.py"], cwd=cible)
    for l in sortie.splitlines():
        dire("gris", l.strip())
    dire("ok" if code == 0 else "non",
         "figures produced" if code == 0 else "the generator failed")


def main() -> int:
    ap = argparse.ArgumentParser(description="Installs the private dashboard.")
    ap.add_argument("--installer", action="store_true",
                    help="actually do it (without this flag, nothing is written)")
    ap.add_argument("--vers", default=".", help="the install directory (default: here)")
    ap.add_argument("--config", default=None, help="the config.json (default: <vers>/tableau-de-bord/config.json)")
    ap.add_argument("--heure", type=int, default=5, help="hour of the refresh (default: 5)")
    ap.add_argument("--sans-tache", action="store_true",
                    help="ne pas toucher au crontab (launchd, systemd, GitHub Actions…)")
    a = ap.parse_args()

    cible = Path(os.path.expanduser(a.vers)).resolve()
    faire = a.installer
    conf_f = Path(a.config) if a.config else cible / "tableau-de-bord" / "config.json"

    print(f"\n{OR}Private dashboard{NET} — {'install' if faire else 'dry run'}")
    print(f"{GRIS}into {cible}{NET}\n")
    if not faire:
        print(f"{GRIS}Nothing will be written. Add --installer to do it.{NET}\n")

    print("── What the machine can do")
    etat = controler()
    if not etat["python"]:
        return 1

    print("\n── The configuration")
    if conf_f.exists():
        conf = json.loads(conf_f.read_text(encoding="utf-8"))
        dire("ok", f"{conf_f}", f"title \"{conf.get('titre', '—')}\", "
                                f"{len(conf.get('sites', []))} site(s)")
    else:
        conf = json.loads(PAQUET["textes"]["tableau-de-bord/config.exemple.json"])
        dire("info", "no config.json — the example will be the starting point",
             "edit tableau-de-bord/config.json, then run again")

    print("\n── The files")
    poser_fichiers(cible, faire)
    if faire and not conf_f.exists():
        conf_f.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(cible / "tableau-de-bord" / "config.exemple.json", conf_f)
        dire("ok", "config.json created from the example")
    faire_icone(cible, conf, faire)

    print("\n── The figures")
    premiers_chiffres(cible, faire)

    print("\n── The service")
    servir(cible, etat, faire)

    print("\n── Private access")
    ouvrir_au_tailnet(etat, faire)

    print("\n── The morning")
    if a.sans_tache:
        dire("gris", "crontab left alone; schedule it as you see fit",
             f"{sys.executable} scripts/tableau-de-bord.py")
    else:
        poser_la_tache(cible, a.heure, faire)

    print()
    if faire:
        code, st = lancer(["tailscale", "serve", "status"]) if etat.get("tailscale") else (1, "")
        adresse = next((l.split()[0] for l in st.splitlines() if l.startswith("https://")), None)
        if adresse:
            print(f"{VERT}Ready.{NET} {adresse}")
            print(f"{GRIS}On iPhone: open it in Safari, then Share → Add to Home Screen.{NET}")
        else:
            print(f"{VERT}Ready.{NET} http://127.0.0.1:{PORT}")
    else:
        print(f"{OR}Dry run finished.{NET} Run again with --installer to do it.")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
