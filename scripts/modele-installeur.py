def dire(etat: str, texte: str, detail: str = "") -> None:
    c = {"ok": VERT, "non": ROUGE, "info": OR, "gris": GRIS}.get(etat, "")
    marque = {"ok": "✓", "non": "✗", "info": "•", "gris": " "}.get(etat, " ")
